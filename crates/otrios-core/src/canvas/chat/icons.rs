// Clockwise, starting at the right. Reuse these points for rings, arcs and gears.
const UNIT: [[f32; 2]; 16] = [
    [1., 0.],
    [0.924, 0.383],
    [0.707, 0.707],
    [0.383, 0.924],
    [0., 1.],
    [-0.383, 0.924],
    [-0.707, 0.707],
    [-0.924, 0.383],
    [-1., 0.],
    [-0.924, -0.383],
    [-0.707, -0.707],
    [-0.383, -0.924],
    [0., -1.],
    [0.383, -0.924],
    [0.707, -0.707],
    [0.924, -0.383],
];
#[derive(Default)]
struct Lines(Vec<Vec<[f32; 2]>>);
impl Lines {
    fn path(&mut self, points: &[[f32; 2]]) {
        self.0.push(points.to_vec());
    }
    fn line(&mut self, a: [f32; 2], b: [f32; 2]) {
        self.path(&[a, b]);
    }
    fn ring(&mut self, x: f32, y: f32, rx: f32, ry: f32) {
        self.arc(x, y, rx, ry, 0, 16);
    }
    fn arc(&mut self, x: f32, y: f32, rx: f32, ry: f32, start: usize, end: usize) {
        self.0.push(
            (start..=end)
                .map(|i| [x + UNIT[i % 16][0] * rx, y + UNIT[i % 16][1] * ry])
                .collect(),
        );
    }
    fn box_at(&mut self, x: f32, y: f32, w: f32, h: f32) {
        self.path(&[[x, y], [x + w, y], [x + w, y + h], [x, y + h], [x, y]]);
    }
    fn dot(&mut self, x: f32, y: f32) {
        self.line([x - 0.35, y], [x + 0.35, y]);
    }
    fn watch(&mut self) {
        self.ring(16., 18., 10., 10.);
        self.box_at(13., 2., 6., 5.);
    }
}
pub fn name(id: u8) -> String {
    NAMES[usize::from(id % 64)].into()
}
