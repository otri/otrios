pub fn avatar(id: u8, base: u32, size: f32) -> SceneNode {
    let factor = size / 32.;
    let children = drawing(id)
        .0
        .into_iter()
        .enumerate()
        .map(|(i, points)| {
            node(
                base + 1 + i as u32,
                Rect::new(0., 0., size, size),
                Primitive::Path {
                    points: points
                        .into_iter()
                        .map(|[x, y]| [x * factor, y * factor])
                        .collect(),
                    width: 1.6 * factor,
                    color: COPPER,
                },
            )
        })
        .collect();
    canvas(base, Rect::new(0., 0., size, size), children)
}
