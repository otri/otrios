"""Generate the browser source module from the native canonical Slug shaders."""
import argparse
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
parts = ['// SPDX-License-Identifier: MIT AND Apache-2.0\n// Generated by scripts/generate-slug-shaders.py; see canonical shader attribution.\n']
for name, filename in [('slugVertex', 'slug.vert'), ('slugFragment', 'slug.frag')]:
    text = (root / 'crates/otrios-linux-display/shaders' / filename).read_text()
    parts.append(f'export const {name} = {json.dumps(text)};\n')
output = root / 'web/shared/slug-shaders.mjs'
text = ''.join(parts)
if args.check:
    if output.read_text() != text:
        raise SystemExit('Stale browser Slug shaders; regenerate with scripts/generate-slug-shaders.py')
else:
    output.write_text(text)

license_source = root / 'crates/otrios-linux-display/shaders/Slug-LICENSE.txt'
license_output = root / 'web/shared/Slug-LICENSE.txt'
if args.check:
    if license_output.read_bytes() != license_source.read_bytes():
        raise SystemExit('Stale browser Slug license notice')
else:
    license_output.write_bytes(license_source.read_bytes())
